"""Application settings, read from environment variables and backend/.env."""

from functools import lru_cache
from pathlib import Path

from pydantic import Field, field_validator
from pydantic_settings import BaseSettings, SettingsConfigDict

BACKEND_DIR = Path(__file__).resolve().parent.parent


class Settings(BaseSettings):
    model_config = SettingsConfigDict(
        env_file=BACKEND_DIR / ".env", env_file_encoding="utf-8", extra="ignore"
    )

    # postgresql+psycopg://user:password@host:port/database
    database_url: str = "postgresql+psycopg://localhost:5432/ai_image_studio"
    # Signs nothing by itself: it is the root key from which the key that encrypts
    # provider API keys is derived. Generated by scripts/setup.sh.
    app_secret_key: str = Field(default="", min_length=0)
    # Generated images and reference uploads (one folder per user).
    storage_dir: Path = BACKEND_DIR / "storage"

    session_days: int = 30
    # The owner's choice for now: the studio opens without a sign-in screen and uses the first
    # account on this Mac (created automatically when there is none). AUTO_LOGIN=false brings
    # the sign-in screen back.
    auto_login: bool = True
    max_upload_mb: int = 10
    # How many generation jobs run at the same time (each may hold several requests).
    worker_concurrency: int = 4
    # A provider request that is not finished after this many seconds is failed.
    job_timeout_seconds: int = 900
    # ComfyUI runs: the first run loads ~17 GB of Krea 2 weights, so allow longer.
    comfy_timeout_seconds: int = 1800

    # Only for tests and local development against a fake provider. Never set in production.
    wavespeed_base_url: str = "https://api.wavespeed.ai"
    atlas_base_url: str = "https://api.atlascloud.ai"
    runpod_rest_url: str = "https://rest.runpod.io/v1"
    runpod_graphql_url: str = "https://api.runpod.io/graphql"
    runpod_serverless_url: str = "https://api.runpod.ai/v2"
    runpod_proxy_url: str = "https://{pod_id}-{port}.proxy.runpod.net"
    huggingface_url: str = "https://huggingface.co"

    @field_validator("storage_dir", mode="before")
    @classmethod
    def _resolve_storage(cls, value: str | Path) -> Path:
        path = Path(value)
        return path if path.is_absolute() else (BACKEND_DIR / path).resolve()


@lru_cache
def get_settings() -> Settings:
    return Settings()
